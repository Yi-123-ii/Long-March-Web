// node tools/build-journey-media.mjs --ffmpeg /path/to/ffmpeg [--sharp /path/to/sharp]
// Keep supplied sources intact; generate 720p web delivery copies and a content-hashed lookup.
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),require=createRequire(import.meta.url);
const args=process.argv.slice(2),arg=name=>args[args.indexOf(name)+1];
if(!args.includes('--ffmpeg'))throw Error('Pass --ffmpeg with a local FFmpeg binary');
const sharp=require(args.includes('--sharp')?arg('--sharp'):'sharp'),ffmpeg=arg('--ffmpeg');
const D=require('../modules/c/assets/yudu-data.js'),base=path.join(root,'modules/c');
const movies=new Set(['assets/prologue/yudu-arrival-v022.mp4',...D.nodes.filter(n=>n.nativeAudio).map(n=>n.video||D.video)]);
const images=new Set([...Object.values(D.images),...D.nodes.flatMap(n=>[n.poster,n.hold])].filter(p=>p?.endsWith('.png')));
const mapping={},records=[];let originalBytes=0,webBytes=0;
await mkdir(path.join(base,'assets/stream'),{recursive:true});
for(const source of [...movies,...images]){
 const original=await readFile(path.join(base,source)),video=movies.has(source);
 const hash=createHash('sha256').update(original).update(video?'h264-crf25-720p-aac96-v1':'webp-q87-v1').digest('hex').slice(0,10);
 const target=`assets/stream/${path.basename(source,path.extname(source))}-${hash}.${video?'mp4':'webp'}`;
 try{await stat(path.join(base,target));}catch{
  if(video)await new Promise((resolve,reject)=>{
   const process=spawn(ffmpeg,['-hide_banner','-loglevel','error','-y','-i',path.join(base,source),'-map','0:v:0','-map','0:a:0?','-c:v','libx264','-preset','slow','-crf','25','-maxrate','1400k','-bufsize','2800k','-pix_fmt','yuv420p','-c:a','aac','-b:a','96k','-movflags','+faststart',path.join(base,target)],{windowsHide:true,stdio:['ignore','ignore','pipe']});
   let errors='';process.stderr.on('data',d=>errors+=d);process.on('error',reject);process.on('exit',code=>code===0?resolve():reject(Error(errors)));
  });
  else await sharp(original).webp({quality:87,effort:6}).toFile(path.join(base,target));
 }
 const size=(await stat(path.join(base,target))).size;mapping[source]=target;
 records.push({source,web:target,sha256:createHash('sha256').update(original).digest('hex'),originalBytes:original.length,webBytes:size});
 originalBytes+=original.length;webBytes+=size;
}
// Preserve the approved footer trim and the verified loudness delivery layer.
mapping['assets/audio/xiaoman-narration-v041/XN060.mp3']='assets/review-v053/XN060-clean.mp3';
const levels=JSON.parse(await readFile(path.join(base,'assets/audio/leveled-v056/manifest.json'),'utf8'));
for(const row of levels.recordings.filter(r=>r.processed)){
 const original=await readFile(path.join(base,row.file));
 if(createHash('sha256').update(original).digest('hex')!==row.original_sha256)throw Error('Recheck loudness after source changes: '+row.file);
 await stat(path.join(base,row.playback));
 for(const source of row.paths)mapping[source]=row.playback;
}
await writeFile(path.join(base,'assets/journey-media.js'),`// Generated by tools/build-journey-media.mjs. Original sources remain unchanged.\n(function(root){const media=${JSON.stringify(mapping,null,1)};if(typeof module==='object'&&module.exports)module.exports=media;else root.JourneyMedia=media;})(typeof window==='undefined'?globalThis:window);\n`);
await mkdir(path.join(root,'docs/journey'),{recursive:true});
await writeFile(path.join(root,'docs/journey/web-media.json'),JSON.stringify({video:{codec:'H.264',crf:25,maxrate:'1400k',audio:'AAC 96k',faststart:true,dimensions:'source 1280×720',timing:'original frame rate and duration'},image:{format:'WebP',quality:87,dimensions:'original'},originalBytes,webBytes,files:records},null,2)+'\n');
console.log(JSON.stringify({movies:movies.size,images:images.size,originalBytes,webBytes}));
