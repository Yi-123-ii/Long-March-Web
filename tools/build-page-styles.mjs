import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const configPath = path.join(root, 'tools/page-styles.json');
const pages = ['index.html', 'chronicle.html', 'inheritance.html', 'post-office.html', 'modules/c/journey.html'];
const href = tag => tag.match(/href="([^"?]+)/)?.[1];
const slash = value => value.split(path.sep).join('/');
async function save(file, content) {
  if (await readFile(file, 'utf8').catch(() => '') !== content) await writeFile(file, content);
}
export async function buildPageStyles() {
  // Static copy needs only the existing site subsets. Keep the complete input
  // character coverage in a second sheet used by the letter editor after paint.
  const fontPath = path.join(root, 'assets/css/fonts.css');
  const inputPath = path.join(root, 'assets/css/fonts-input.css');
  const fonts = await readFile(fontPath, 'utf8');
  const isSite = block => /shanhe-[^"/]*(?:-site-|-critical-)/.test(block);
  let faces = [...fonts.matchAll(/@font-face\s*\{[^}]+\}/g)].map(match => match[0]);
  if (faces.every(isSite)) faces.push(...[...(await readFile(inputPath, 'utf8')).matchAll(/@font-face\s*\{[^}]+\}/g)].map(match => match[0]));
  await save(fontPath, '/* Current-site fonts; generated by build-page-styles.mjs. */\n' + faces.filter(isSite).join('\n') + '\n');
  await save(inputPath, '/* Complete input character coverage; loaded after first paint in the letter editor. */\n' + faces.filter(block => !isSite(block)).join('\n') + '\n');
  let config = JSON.parse(await readFile(configPath, 'utf8').catch(() => 'null'));
  if (!config) {
    config = {};
    for (const page of pages) {
      const html = await readFile(path.join(root, page), 'utf8');
      config[page] = [...html.matchAll(/<link\b[^>]*>/g)].map(match => match[0])
        .filter(tag => /rel="stylesheet"/.test(tag) && !tag.includes('fonts.css'))
        .map(tag => slash(path.relative(root, path.resolve(root, path.dirname(page), href(tag)))));
    }
    await save(configPath, JSON.stringify(config, null, 2) + '\n');
  }
  const directory = path.join(root, 'assets/css/pages');
  await mkdir(directory, { recursive: true });
  for (const [page, sources] of Object.entries(config)) {
    const name = page === 'index.html' ? 'home' : path.basename(page, '.html');
    const file = path.join(directory, name + '.css');
    const styles = await Promise.all(sources.map(async source => {
      const original = path.join(root, source);
      const css = (await readFile(original, 'utf8')).replace(/@charset\s+["'][^"']+["'];/g, '');
      return '/* ' + source + ' */\n' + css.replace(/url\(\s*(?:(["'])(.*?)\1|([^)]*))\s*\)/gs, (match, quote, quoted, bare) => {
        const ref = (quoted ?? bare).trim();
        if (!ref || /^(?:[a-z]+:|\/|#)/i.test(ref)) return match;
        const [, asset, suffix = ''] = ref.match(/^([^?#]+)(.*)$/s);
        return 'url("' + slash(path.relative(directory, path.resolve(path.dirname(original), asset))) + suffix + '")';
      });
    }));
    const content = '/* Generated by tools/build-page-styles.mjs; edit the original stylesheets. */\n' + styles.join('\n');
    const hash = createHash('sha256').update(content).digest('hex').slice(0, 12);
    await save(file, content);
    const relative = slash(path.relative(path.resolve(root, path.dirname(page)), file));
    const bundled = `<link rel="stylesheet" data-page-styles href="${relative}?v=${hash}" />`;
    const sourcePaths = new Set(sources);
    let placed = false;
    const htmlPath = path.join(root, page);
    const html = await readFile(htmlPath, 'utf8');
    const next = html.replace(/<link\b[^>]*>/g, tag => {
      const ref = href(tag);
      if (!ref || !/rel="stylesheet"/.test(tag)) return tag;
      const local = slash(path.relative(root, path.resolve(root, path.dirname(page), ref)));
      if (!tag.includes('data-page-styles') && !sourcePaths.has(local)) return tag;
      if (placed) return '';
      placed = true;
      return bundled;
    });
    if (!placed) throw Error('Missing stylesheet entry: ' + page);
    await save(htmlPath, next);
  }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildPageStyles();
  console.log('Built five page stylesheets in their original cascade order');
}
